package com.github.guardian.enums;

/**
 * 业务方法抛异常时，幂等占位怎么处理。
 */
public enum ExceptionPolicy {

    /**
     * 释放占位，允许立即重试。默认。
     *
     * <p>选它的理由：业务失败通常应该可重试。风险是"业务其实已部分生效"时
     * 重试会重复执行 —— 这种情况要靠业务侧事务保证，不能靠幂等框架猜。
     */
    RELEASE,

    /**
     * 保留占位直到 ttl 过期，期间同 key 视为重复提交。
     *
     * <p>适用于"失败了也不能重试"的场景（如已对外发起支付）。
     */
    KEEP
}
